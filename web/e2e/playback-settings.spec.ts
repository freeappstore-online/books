import { test, expect, stubHuggingFace, audio, bar, expectPlaying, headerPlay, SLUG } from './fixtures'

const sleepSettings = (page: import('@playwright/test').Page) => page.getByRole('region', { name: 'Sleep timer', exact: true }).first()

test.beforeEach(async ({ context, baseURL }) => { await stubHuggingFace(context, baseURL!) })

test('settings offers custom timers before playing, validates input, and remembers preferences', async ({ page }) => {
  await page.goto('/settings')
  await expect(page.getByText(/On: keep playing narrated chapters/)).toBeVisible()
  const follow = page.getByRole('switch', { name: 'Scroll with audio' })
  await expect(follow).toBeChecked()
  await follow.uncheck()
  const sleep = sleepSettings(page)
  const input = sleep.getByLabel('Custom duration (minutes)')
  for (const invalid of ['', '0', '-1', '1.5', '1441']) {
    await input.fill(invalid)
    await expect(sleep.getByRole('button', { name: 'Start timer' })).toBeDisabled()
  }
  await input.fill('90')
  await sleep.getByRole('button', { name: 'Start timer' }).click()
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('Sleep timer: 1:30:00')
  await sleep.getByRole('button', { name: '+15 minutes', exact: true }).click()
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('Sleep timer: 1:45:00')
  await sleep.getByLabel('Stop playback after').selectOption('chapter')
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('Sleep timer: end of chapter')
  await sleep.getByRole('button', { name: 'Turn off timer' }).click()
  await input.fill('27')
  await sleep.getByRole('button', { name: 'Start timer' }).click()
  await page.reload()
  await expect(follow).not.toBeChecked()
  await expect(input).toHaveValue('27')
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('No sleep timer')
})

test('timer stays in sync across settings and player, pauses, fades, expires and restores volume', async ({ page }) => {
  let now = Date.now()
  await page.clock.setFixedTime(now)
  await page.goto(`/read/${SLUG}`)
  await headerPlay(page).click()
  await expectPlaying(page, 0)
  await page.getByRole('button', { name: 'Sleep timer', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Custom timer and settings…' }).click()
  const sleep = sleepSettings(page)
  await sleep.getByLabel('Custom duration (minutes)').fill('1')
  await sleep.getByRole('button', { name: 'Start timer' }).click()
  await page.clock.setFixedTime(now += 30_000)
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('Sleep timer: 0:30')
  await expect(bar(page).getByRole('button', { name: 'Sleep timer: 0:30', exact: true })).toBeVisible()
  await bar(page).getByRole('button', { name: 'Pause', exact: true }).click()
  await page.clock.setFixedTime(now += 120_000)
  await page.waitForTimeout(1200)
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('Sleep timer: 0:30')
  await bar(page).getByRole('button', { name: 'Resume', exact: true }).click()
  await expectPlaying(page, 0)
  await page.clock.setFixedTime(now += 25_000)
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('Sleep timer: 0:05')
  await page.clock.setFixedTime(now += 6000)
  await expect(bar(page).getByRole('button', { name: 'Resume', exact: true })).toBeVisible()
  await expect(sleep.locator('[data-sleep-status]')).toHaveText('No sleep timer')
  expect((await audio(page))!.paused).toBe(true)
  await bar(page).getByRole('button', { name: 'Resume', exact: true }).click()
  await expectPlaying(page, 0)
  await expect.poll(() => page.evaluate(() => (window as unknown as { __audios: HTMLAudioElement[] }).__audios[0].volume)).toBe(1)
  // Cancel in Settings also clears the bar's timer.
  await sleep.getByLabel('Stop playback after').selectOption('15')
  await sleep.getByRole('button', { name: 'Turn off timer' }).click()
  await expect(bar(page).getByRole('button', { name: 'Sleep timer', exact: true })).toBeVisible()
})

for (const width of [390, 1200]) {
  test(`read-along stays visible and only page scrolling suspends following at ${width}px`, async ({ page, isMobile }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto(`/read/${SLUG}`)
    await headerPlay(page).click()
    await expectPlaying(page, 0)
    const word = page.locator('[data-readalong="word"]').first()
    const follow = page.locator('[data-shortcut="follow"]')
    await expect(word).toBeVisible()
    // Seek deep into the chapter: the word has to be scrolled into the reading area.
    for (let i = 0; i < 3; i++) await page.getByLabel('Forward 30 seconds').click()
    await expect.poll(async () => (await audio(page))!.t).toBeGreaterThan(85)
    await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(500)
    const expectVisible = async () => {
      await expect.poll(() => word.evaluate(el => {
        const rect = el.getBoundingClientRect()
        const top = document.querySelector('[data-reader-top]')!.getBoundingClientRect().bottom
        const bottom = document.querySelector('[data-audio-player]')!.getBoundingClientRect().top
        return rect.top >= top && rect.bottom <= bottom
      })).toBe(true)
    }
    await expectVisible()
    await bar(page).getByRole('button', { name: 'Show chapters' }).click()
    await bar(page).getByRole('button', { name: 'Listening', exact: true }).click()
    await bar(page).getByLabel('Custom duration (minutes)').focus()
    await page.keyboard.press('ArrowUp')
    await page.locator('#player-panel').dispatchEvent('wheel', { deltaY: 150 })
    await expect(follow).toHaveCount(0)
    await expectVisible()
    await bar(page).getByRole('button', { name: 'Hide chapters' }).click()
    await page.setViewportSize({ width, height: 600 })
    await expectVisible()
    // A page-scroll gesture suspends following (desktop Firefox has no TouchEvent).
    await page.locator('[data-chapter-text]').dispatchEvent(isMobile ? 'touchmove' : 'wheel', { deltaY: 200 })
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
    await expect(follow).toBeVisible()
    await page.waitForTimeout(500)
    expect(await page.evaluate(() => scrollY)).toBe(0)
    await follow.click()
    await expect(follow).toHaveCount(0)
    await expectVisible()
    await page.screenshot({ path: `test-results/follow-${width}.png` })
  })
}

test('scroll preference persists and Follow audio explicitly turns it back on', async ({ page }) => {
  await page.goto('/settings')
  await page.getByRole('switch', { name: 'Scroll with audio' }).uncheck()
  await page.goto(`/read/${SLUG}`)
  await headerPlay(page).click()
  await expectPlaying(page, 0)
  await page.getByLabel('Forward 30 seconds').click()
  await expect(page.locator('[data-shortcut="follow"]')).toBeVisible()
  await page.waitForTimeout(500)
  expect(await page.evaluate(() => scrollY)).toBeLessThan(500)
  await page.locator('[data-shortcut="follow"]').click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('bp-follow-audio'))).toBe('1')
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(500)
})
